const LanguageContext = createContext<LanguageContextType | undefined>(undefined)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('ar')
  const [mounted, setMounted] = useState(false)

  useEffect(() => {
    setMounted(true)
    const storedLang = localStorage.getItem('clinic_os_lang') as Language | null
    if (storedLang === 'en' || storedLang === 'ar') {
      setLanguageState(storedLang)
      applyLanguage(storedLang)
    } else {
      applyLanguage('ar')
    }
  }, [])

  const applyLanguage = (lang: Language) => {
    if (typeof document === 'undefined') return
    const root = document.documentElement
    root.lang = lang
    const dir = lang === 'ar' ? 'rtl' : 'ltr'
    root.dir = dir
    if (dir === 'rtl') {
      root.classList.add('rtl')
      root.classList.remove('ltr')
    } else {
      root.classList.add('ltr')
      root.classList.remove('rtl')
    }
  }

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    localStorage.setItem('clinic_os_lang', lang)
    applyLanguage(lang)
  }

  const toggleLanguage = () => {
    const next = language === 'ar' ? 'en' : 'ar'
    setLanguage(next)
  }

  // Translates dynamic terms from database like 'كشف عادي' or 'الفرع الرئيسي'
  const tDynamic = (value: string | undefined | null): string => {
    if (!value) return ''
    const str = String(value).trim()
    if (!str) return ''
    const dict = dynamicTerms[language]
    if (dict && dict[str]) {
      return dict[str]
    }
    // Also check direct dictionary
    const langDict = translations[language]
    if (langDict && langDict[str]) {
      return langDict[str]
    }
    return str
  }

  const t = (key: string, fallback?: string): string => {
    const dict = translations[language] || translations.ar
    if (dict && dict[key]) {
      return dict[key]
    }

    // Check dynamic terms dictionary for the key
    const dyn = dynamicTerms[language]
    if (dyn && dyn[key]) {
      return dyn[key]
    }

    // Check dynamic terms for fallback if in English
    if (language === 'en' && fallback && dyn && dyn[fallback]) {
      return dyn[fallback]
    }

    // Fallback to Arabic dict if key missing in English
    if (translations.ar && translations.ar[key]) {
      return translations.ar[key]
    }

    return fallback || key
  }

  const dir: 'rtl' | 'ltr' = language === 'ar' ? 'rtl' : 'ltr'
  const isRtl = dir === 'rtl'

  return (
    <LanguageContext.Provider value={{ language, dir, isRtl, setLanguage, toggleLanguage, t, tDynamic }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }
  return context
}
